package io.github.salomax.neotool.banking.model.account

import io.github.salomax.neotool.banking.domain.account.ConnectionStatus
import io.github.salomax.neotool.banking.domain.account.FinancialAccountSubtype
import io.github.salomax.neotool.banking.domain.account.FinancialAccountType
import io.github.salomax.neotool.common.entity.BaseEntity
import jakarta.persistence.CascadeType
import jakarta.persistence.Column
import jakarta.persistence.Entity
import jakarta.persistence.EnumType
import jakarta.persistence.Enumerated
import jakarta.persistence.Id
import jakarta.persistence.OneToOne
import jakarta.persistence.Table
import org.hibernate.annotations.Generated
import org.hibernate.generator.EventType
import java.time.Instant
import java.util.UUID

/**
 * JPA entity for banking.financial_accounts (base table of CTI).
 * Id is generated by the database (DEFAULT uuidv7()) and read back after insert.
 */
@Entity
@Table(name = "financial_accounts", schema = "banking")
open class FinancialAccountEntity(
    @Id
    @Generated(event = [EventType.INSERT])
    @Column(columnDefinition = "uuid", insertable = false, updatable = false)
    override val id: UUID? = null,
    @Column(name = "account_id", nullable = false)
    open var accountId: UUID,
    @Column(name = "created_by_user_id", nullable = false)
    open var createdByUserId: UUID,
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    open var type: FinancialAccountType,
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 40)
    open var subtype: FinancialAccountSubtype,
    @Column(nullable = false, length = 100)
    open var name: String,
    @Column(name = "currency_code", nullable = false, length = 3)
    open var currencyCode: String = "BRL",
    @Column(name = "include_in_net_worth", nullable = false)
    open var includeInNetWorth: Boolean = true,
    @Column(name = "include_in_dashboard", nullable = false)
    open var includeInDashboard: Boolean = true,
    @Column(name = "include_cash_in_allocation", nullable = false)
    open var includeCashInAllocation: Boolean = true,
    @Column(name = "issuer_id")
    open var issuerId: UUID? = null,
    @Column(name = "theme_color", length = 7)
    open var themeColor: String? = null,
    @Column(name = "logo_key")
    open var logoKey: String? = null,
    @Column(name = "issuer_name", length = 100)
    open var issuerName: String? = null,
    @Column(name = "issuer_country", length = 2)
    open var issuerCountry: String? = null,
    @Column(name = "issuer_compe_code", length = 3)
    open var issuerCompeCode: String? = null,
    @Column(name = "issuer_ispb", length = 8)
    open var issuerIspb: String? = null,
    @Column(name = "card_last_four_digits", length = 4)
    open var cardLastFourDigits: String? = null,
    @Enumerated(EnumType.STRING)
    @Column(name = "connection_status", length = 30)
    open var connectionStatus: ConnectionStatus? = null,
    @Column(name = "consent_expires_at")
    open var consentExpiresAt: Instant? = null,
    @Column(name = "last_sync_at")
    open var lastSyncAt: Instant? = null,
    @Column(name = "provider_item_id")
    open var providerItemId: String? = null,
    @Column(name = "deleted_at")
    open var deletedAt: Instant? = null,
    @Column(name = "created_at", nullable = false)
    open var createdAt: Instant = Instant.now(),
    @Column(name = "updated_at", nullable = false)
    open var updatedAt: Instant = Instant.now(),
    @OneToOne(mappedBy = "account", cascade = [CascadeType.ALL], optional = true)
    open var bankData: FinancialAccountBankDataEntity? = null,
    @OneToOne(mappedBy = "account", cascade = [CascadeType.ALL], optional = true)
    open var cardData: FinancialAccountCardDataEntity? = null,
) : BaseEntity<UUID?>(id)
